            "# CELL 9: Multi-Task ResNet-18 (3 heads)\n",
            "class UnbreakableCNN62(nn.Module):\n",
            "    def __init__(self, num_classes=62):\n",
            "        super().__init__()\n",
            "        backbone = torchvision.models.resnet18(weights=None)\n",
            "        backbone.conv1 = nn.Conv2d(1, 64, kernel_size=7, stride=2, padding=3, bias=False)\n",
            "        feat_dim = backbone.fc.in_features\n",
            "        backbone.fc = nn.Identity()\n",
            "        self.backbone = backbone\n",
            "        # HEAD 1: Character Identity (digits + upper + lower)\n",
            "        self.identity_head = nn.Sequential(\n",
            "            nn.BatchNorm1d(feat_dim), nn.Dropout(0.35),\n",
            "            nn.Linear(feat_dim, 256), nn.ReLU(),\n",
            "            nn.Linear(256, num_classes)\n",
            "        )\n",
            "        # HEAD 2: Orientation (0=Normal / 1=Reversal / 2=Corrected)\n",
            "        self.orientation_head = nn.Sequential(\n",
            "            nn.Dropout(0.2), nn.Linear(feat_dim, 3)\n",
            "        )\n",
            "        # HEAD 3: Dyslexia Risk Score (0.0 safe → 1.0 high-risk)\n",
            "        self.risk_head = nn.Sequential(\n",
            "            nn.Dropout(0.2), nn.Linear(feat_dim, 1), nn.Sigmoid()\n",
            "        )\n\n",
            "    def forward(self, x):\n",
            "        f = self.backbone(x)\n",
            "        return self.identity_head(f), self.orientation_head(f), self.risk_head(f)\n\n",
            "model = UnbreakableCNN62(num_classes=NUM_CLASSES).to(DEVICE)\n",
            "total = sum(p.numel() for p in model.parameters() if p.requires_grad)\n",
            "print(f'Model on {DEVICE} | Trainable params: {total:,}')\n",
