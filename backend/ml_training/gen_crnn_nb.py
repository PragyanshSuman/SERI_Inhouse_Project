            "# CELL 8: Inference and Dyslexia Risk Index Calculus\n",
            "def decode_ctc(preds):\n",
            "    # Greedy Decode\n",
            "    pred_indices = torch.argmax(preds, dim=2).permute(1, 0) # [B, T]\n",
            "    decoded_words = []\n",
            "    for p in pred_indices:\n",
            "        word = ''\n",
            "        prev = 0\n",
            "        for idx in p:\n",
            "            idx = idx.item()\n",
            "            if idx != 0 and idx != prev:\n",
            "                word += label_to_char(idx)\n",
            "            prev = idx\n",
            "        decoded_words.append(word)\n",
            "    return decoded_words\n",
            "\n",
            "def calculate_dyslexia_risk(ocr_text, target_text):\n",
            "    \"\"\"\n",
            "    Applies the P_dyslexia(w) formula comparing OCR transcription vs expected word.\n",
            "    \"\"\"\n",
            "    if ocr_text == target_text:\n",
            "        return 0.0, \"None\"\n",
            "    \n",
            "    # Calibrated Weights from paper\n",
            "    alpha, beta, gamma = 1.0, 0.8, 1.2 \n",
            "    score = 0.0\n",
            "    detected_errors = []\n",
            "    \n",
            "    # 1. Transposition check (saw vs was)\n",
            "    if sorted(ocr_text) == sorted(target_text) and len(ocr_text) == len(target_text):\n",
            "        score += gamma * 100\n",
            "        detected_errors.append(\"Transposition\")\n",
            "        return min(100.0, score), \" + \".join(detected_errors)\n",
            "    \n",
            "    # 2. Reversal/Substitution checks\n",
            "    reversals = [('b','d'), ('p','q'), ('m','w'), ('n','u')]\n",
            "    pairs = []\n",
            "    for rev in reversals:\n",
            "        pairs.extend([rev, (rev[1], rev[0])])\n",
            "        \n",
            "    # Very simple Levenshtein-like linear scan for demo:\n",
            "    for o, t in zip(ocr_text, target_text):\n",
            "        if (o, t) in pairs:\n",
            "            score += (alpha / len(target_text)) * 100\n",
            "            detected_errors.append(f\"{t}→{o} reversal\")\n",
            "        elif o != t:\n",
            "            # Unrelated spelling error\n",
            "            pass\n",
            "            \n",
            "    if not detected_errors:\n",
            "        detected_errors.append(\"Generic Spanning Error\")\n",
            "        score += 5.0 # Baseline penalty\n",
            "        \n",
            "    return min(100.0, score), \" + \".join(detected_errors)\n",
            "\n",
            "model.eval()\n",
            "with torch.no_grad():\n",
