            "# CELL 4: Synthetic Word & Error Generator\n",
            "class SyntheticWordDataset(Dataset):\n",
            "    def __init__(self, char_dict, word_list, num_samples=10000):\n",
            "        self.char_dict = char_dict\n",
            "        self.word_list = [w.lower() for w in word_list if 3 <= len(w) <= MAX_WORD_LEN and w.isalpha()]\n",
            "        self.num_samples = num_samples\n",
            "\n",
            "    def __len__(self):\n",
            "        return self.num_samples\n",
            "\n",
            "    def __getitem__(self, idx):\n",
            "        # Pick a random word\n",
            "        word = random.choice(self.word_list)\n",
            "        \n",
            "        # 10% chance to simulate a dyslexic transposition (e.g. \"was\" -> \"saw\")\n",
            "        error_injected = False\n",
            "        actual_text = word\n",
            "        if random.random() < 0.10 and len(word) > 3:\n",
            "            s_idx = random.randint(0, len(word)-2)\n",
            "            w_list = list(word)\n",
            "            w_list[s_idx], w_list[s_idx+1] = w_list[s_idx+1], w_list[s_idx]\n",
            "            actual_text = \"\".join(w_list)\n",
            "            error_injected = True\n",
            "            \n",
            "        # Blank image canvas\n",
            "        word_img = np.zeros((28, MAX_WORD_LEN * 28), dtype=np.uint8)\n",
            "        \n",
            "        # Stitch characters\n",
            "        cursor = 0\n",
            "        for c in actual_text:\n",
            "            if len(self.char_dict[c]) == 0:\n",
            "                continue\n",
            "            c_img = random.choice(self.char_dict[c])\n",
            "            word_img[0:28, cursor:cursor+28] = c_img\n",
            "            cursor += random.randint(18, 22) # Overlap cursive spacing\n",
            "            \n",
            "        # Crop and resize to exactly 32x128 for the CRNN\n",
            "        word_img = word_img[:, :cursor+5]\n",
            "        pil_img = transforms.ToPILImage()(word_img)\n",
            "        pil_img = pil_img.resize((IMG_WIDTH, IMG_HEIGHT))\n",
            "        tensor_img = transforms.ToTensor()(pil_img)\n",
            "        tensor_img = (tensor_img - 0.5) / 0.5 # Normalize\n",
            "        \n",
            "        # Generate CTC labels\n",
            "        labels = [char_to_label(c) for c in actual_text]\n",
            "        \n",
            "        return tensor_img, labels, actual_text, word, error_injected\n",
