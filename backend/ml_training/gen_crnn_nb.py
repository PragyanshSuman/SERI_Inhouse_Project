            "Here we implement the formulas strictly matching the mathematical blueprint of the journal paper:\n",
            "$$P_{dyslexia}(w) = \\frac{1}{N} \\sum_{i=1}^{N} \\left[ \\alpha \\cdot R_i + \\beta \\cdot M_i + \\gamma \\cdot T_i \\right] \\times 100\\%$$"
