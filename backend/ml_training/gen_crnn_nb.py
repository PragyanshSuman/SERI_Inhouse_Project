            "# CELL 6: Micro-CRNN Architecture\n",
            "class MicroCRNN(nn.Module):\n",
            "    def __init__(self, num_classes):\n",
            "        super(MicroCRNN, self).__init__()\n",
            "        # CNN Feature Extractor (Input: 1 x 32 x 128)\n",
            "        self.cnn = nn.Sequential(\n",
            "            nn.Conv2d(1, 32, kernel_size=3, padding=1), nn.ReLU(),\n",
            "            nn.MaxPool2d(2, 2), # -> 16 x 64\n",
            "            nn.Conv2d(32, 64, kernel_size=3, padding=1), nn.ReLU(),\n",
            "            nn.MaxPool2d(2, 2), # -> 8 x 32\n",
            "            nn.Conv2d(64, 128, kernel_size=3, padding=1), nn.BatchNorm2d(128), nn.ReLU(),\n",
            "            nn.MaxPool2d((2, 1)) # -> 4 x 32 (We keep spatial width for sequence!)\n",
            "        )\n",
            "        # RNN Sequence Modeler\n",
            "        self.rnn = nn.LSTM(input_size=128 * 4, hidden_size=128, bidirectional=True, batch_first=True)\n",
            "        \n",
            "        # Classifier\n",
            "        self.fc = nn.Linear(256, num_classes)\n",
            "\n",
            "    def forward(self, x):\n",
            "        # 1. Feature Extraction: [B, 1, 32, 128] -> [B, 128, 4, 32]\n",
            "        conv = self.cnn(x)\n",
            "        b, c, h, w = conv.size()\n",
            "        \n",
            "        # 2. Reshape for RNN: [Batch, Width(Time), Channels*Height]\n",
            "        conv = conv.view(b, c * h, w)\n",
            "        conv = conv.permute(0, 2, 1) # -> [B, 32, 512]\n",
            "        \n",
            "        # 3. Bi-LSTM\n",
            "        out, _ = self.rnn(conv) # -> [B, 32, 256]\n",
            "        \n",
            "        # 4. Dense to characters\n",
            "        out = self.fc(out) # -> [B, 32, num_classes]\n",
            "        \n",
            "        # 5. CTC Loss expects log_softmax and specific shape [Time, Batch, Classes]\n",
            "        out = out.permute(1, 0, 2)\n",
            "        return F.log_softmax(out, dim=2)\n",
            "\n",
            "model = MicroCRNN(NUM_CLASSES).to(DEVICE)\n",
