            "# CELL 10: Focal Loss + Training Loop\n",
            "# KEY: Kaggle samples have char_label = -1 (unknown letter).\n",
            "# We skip identity loss for those samples, training only ori + risk heads.\n\n",
            "class FocalLoss(nn.Module):\n",
            "    def __init__(self, gamma=2.0):\n",
            "        super().__init__()\n",
            "        self.gamma = gamma\n",
            "        self.ce = nn.CrossEntropyLoss(reduction='none')\n",
            "    def forward(self, logits, targets):\n",
            "        ce = self.ce(logits, targets)\n",
            "        return ((1 - torch.exp(-ce)) ** self.gamma * ce).mean()\n\n",
            "criterion_id  = FocalLoss(gamma=2.0).to(DEVICE)\n",
            "criterion_ori = nn.CrossEntropyLoss().to(DEVICE)\n",
            "criterion_risk= nn.BCELoss().to(DEVICE)\n",
            "optimizer     = optim.AdamW(model.parameters(), lr=LR, weight_decay=1e-4)\n",
            "scheduler     = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=EPOCHS)\n\n",
            "train_losses, val_accs = [], []\n",
            "best_acc = 0\n\n",
            "for epoch in range(EPOCHS):\n",
            "    model.train()\n",
            "    running = 0\n",
            "    for batch in tqdm(train_loader, desc=f'Ep {epoch+1}/{EPOCHS}', leave=False):\n",
            "        imgs, labels, oris, risks = batch\n",
            "        imgs  = imgs.to(DEVICE)\n",
            "        oris  = oris.to(DEVICE)\n",
            "        risks = risks.float().unsqueeze(1).to(DEVICE)\n\n",
            "        optimizer.zero_grad()\n",
            "        out_id, out_ori, out_risk = model(imgs)\n\n",
            "        # Orientation + Risk losses: all samples\n",
            "        loss_ori  = criterion_ori(out_ori, oris)\n",
            "        loss_risk = criterion_risk(out_risk, risks)\n\n",
            "        # Identity loss: only EMNIST samples (label != -1)\n",
            "        known_mask = (labels != -1)\n",
            "        if known_mask.any():\n",
            "            known_labels = labels[known_mask].to(DEVICE)\n",
            "            known_out_id = out_id[known_mask]\n",
            "            loss_id = criterion_id(known_out_id, known_labels)\n",
            "        else:\n",
            "            loss_id = torch.tensor(0.0, device=DEVICE)\n\n",
            "        loss = loss_id + 0.35 * loss_ori + 0.25 * loss_risk\n",
            "        loss.backward()\n",
            "        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)\n",
            "        optimizer.step()\n",
            "        running += loss.item()\n\n",
            "    # Validate (EMNIST only for identity accuracy)\n",
            "    model.eval()\n",
            "    correct, total_n = 0, 0\n",
            "    with torch.no_grad():\n",
            "        for batch in val_loader:\n",
            "            imgs, labels, _, _ = batch\n",
            "            known = labels != -1\n",
            "            if not known.any(): continue\n",
            "            imgs_k   = imgs[known].to(DEVICE)\n",
            "            labels_k = labels[known].to(DEVICE)\n",
            "            out_id, _, _ = model(imgs_k)\n",
            "            correct  += (torch.argmax(out_id, 1) == labels_k).sum().item()\n",
            "            total_n  += labels_k.size(0)\n\n",
            "    acc = 100 * correct / max(total_n, 1)\n",
            "    avg = running / len(train_loader)\n",
            "    train_losses.append(avg)\n",
            "    val_accs.append(acc)\n",
            "    scheduler.step()\n",
            "    if acc > best_acc:\n",
